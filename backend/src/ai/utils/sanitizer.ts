/**
 * Input sanitization, boundaries, and schema validation for AI requests and tool calls.
 */
import { applyExerciseSafetyGuardrail } from "./exerciseSafetyGuard";

export interface SanitizedUserContext {
  username?: string;
  email?: string;
  age?: number | null;
  birthday?: string | null;
  sex?: string | null;
  heightFt?: number | null;
  heightFormatted?: string | null;
  weightLbs?: number | null;
  preferredUnit?: "lbs" | "kgs";
  experienceLevel?: string | null;
  primaryGoals?: string[] | string | null;
  benchPR?: number | null;
  squatPR?: number | null;
  deadliftPR?: number | null;
  activeRoutine?: string | null;
  streak?: number | null;
  workedOutToday?: boolean | null;
}

export interface SanitizedChatInput {
  message: string;
  history: Array<{ role: string; content: string }>;
  userContext?: SanitizedUserContext;
}

/**
 * Strips dangerous prompt injection delimiters and non-printable characters.
 */
function sanitizeString(str: any, maxLength = 100): string {
  if (typeof str !== "string") return "";
  return str
    .replace(/[<>{}|[\]]/g, "") // Strip brackets and angle tags that could spoof prompt blocks
    .replace(/[\x00-\x1F\x7F]/g, "") // Strip control characters
    .trim()
    .slice(0, maxLength);
}

/**
 * Validates and clamps a numeric value within safe boundaries.
 */
function clampNumber(
  val: any,
  min: number,
  max: number,
): number | null {
  if (val === null || val === undefined || val === "") return null;
  const num = Number(val);
  if (isNaN(num)) return null;
  return Math.min(Math.max(num, min), max);
}

/**
 * Validates and sanitizes the incoming chat payload.
 */
export function validateAndSanitizeChatInput(body: any): {
  valid: boolean;
  error?: string;
  data?: SanitizedChatInput;
} {
  if (!body || typeof body !== "object") {
    return { valid: false, error: "Invalid request payload." };
  }

  // 1. Validate Message
  if (typeof body.message !== "string") {
    return { valid: false, error: "Message must be a string." };
  }

  const trimmedMessage = body.message.trim();
  if (trimmedMessage.length === 0) {
    return { valid: false, error: "Message cannot be empty." };
  }

  if (trimmedMessage.length > 1000) {
    return {
      valid: false,
      error: "Message is too long bro! Keep it under 1,000 characters.",
    };
  }

  // 2. Validate and Clamp History (Max 10 messages)
  const rawHistory = Array.isArray(body.history) ? body.history : [];
  const safeHistory = rawHistory
    .slice(-10) // Only keep last 10 messages to prevent token-bloating attacks
    .filter(
      (m: any) =>
        m &&
        typeof m === "object" &&
        (m.role === "user" || m.role === "assistant" || m.role === "model") &&
        typeof m.content === "string",
    )
    .map((m: any) => ({
      role: m.role === "assistant" ? "assistant" : "user",
      content: m.content.slice(0, 2000), // Max 2,000 chars per history message
    }));

  // 3. Sanitize User Context
  let sanitizedContext: SanitizedUserContext | undefined;
  if (body.userContext && typeof body.userContext === "object") {
    const uc = body.userContext;

    let safeGoals: string[] | string | null = null;
    if (Array.isArray(uc.primaryGoals)) {
      safeGoals = uc.primaryGoals
        .map((g: any) => sanitizeString(g, 50))
        .filter(Boolean)
        .slice(0, 10);
    } else if (typeof uc.primaryGoals === "string") {
      safeGoals = sanitizeString(uc.primaryGoals, 200);
    }

    sanitizedContext = {
      username: sanitizeString(uc.username, 50) || "Lifter",
      email: typeof uc.email === "string" ? sanitizeString(uc.email, 100) : undefined,
      age: clampNumber(uc.age, 13, 120),
      birthday: typeof uc.birthday === "string" ? sanitizeString(uc.birthday, 10) : null,
      sex: sanitizeString(uc.sex, 20) || null,
      heightFt: clampNumber(uc.heightFt, 3.0, 8.5),
      heightFormatted: sanitizeString(uc.heightFormatted, 30) || null,
      weightLbs: clampNumber(uc.weightLbs, 50, 700),
      preferredUnit: uc.preferredUnit === "kgs" ? "kgs" : "lbs",
      experienceLevel: sanitizeString(uc.experienceLevel, 30) || null,
      primaryGoals: safeGoals,
      benchPR: clampNumber(uc.benchPR, 0, 1500),
      squatPR: clampNumber(uc.squatPR, 0, 1500),
      deadliftPR: clampNumber(uc.deadliftPR, 0, 1500),
      activeRoutine: sanitizeString(uc.activeRoutine, 80) || null,
      streak: clampNumber(uc.streak, 0, 10000) ?? 0,
      workedOutToday: Boolean(uc.workedOutToday),
    };
  }

  return {
    valid: true,
    data: {
      message: trimmedMessage,
      history: safeHistory,
      userContext: sanitizedContext,
    },
  };
}

/**
 * Validates and sanitizes routine generated by tool calls to prevent corrupt database records.
 */
export function validateAndSanitizeRoutine(
  rawRoutine: any,
  userContext?: SanitizedUserContext,
): any | null {
  if (!rawRoutine || typeof rawRoutine !== "object") return null;

  const routineName =
    typeof rawRoutine.routineName === "string"
      ? sanitizeString(rawRoutine.routineName, 80)
      : "Bro's Custom Workout Routine";

  if (!Array.isArray(rawRoutine.workouts)) return null;

  const validWorkouts = rawRoutine.workouts
    .slice(0, 7) // Max 7 workout days
    .map((w: any, wIdx: number) => {
      if (!w || typeof w !== "object") return null;

      const name = sanitizeString(w.name, 50) || `Workout Day ${wIdx + 1}`;
      const days = Array.isArray(w.days)
        ? w.days
            .map((d: any) => Number(d))
            .filter((d: number) => !isNaN(d) && d >= 1 && d <= 7)
        : [1];

      const rawExercises = Array.isArray(w.exercises) ? w.exercises : [];
      const exercises = rawExercises
        .slice(0, 12) // Max 12 exercises per workout
        .map((ex: any) => {
          if (!ex || typeof ex !== "object") return null;

          const exName = sanitizeString(ex.name, 60);
          if (!exName) return null;

          const muscleGroup = sanitizeString(ex.muscleGroup, 40) || "General";
          const sets = Math.min(Math.max(Number(ex.sets) || 3, 1), 6); // Clamp sets 1-6
          const reps = Math.min(Math.max(Number(ex.reps) || 10, 1), 30); // Clamp reps 1-30
          const weight = Math.min(Math.max(Number(ex.weight) || 0, 0), 1000); // Clamp weight 0-1000

          return {
            name: exName,
            muscleGroup,
            sets,
            reps,
            weight,
          };
        })
        .filter(Boolean);

      return {
        name,
        days: days.length > 0 ? days : [1],
        exercises,
      };
    })
    .filter(Boolean);

  if (validWorkouts.length === 0) return null;

  const structuredRoutine = {
    routineName,
    workouts: validWorkouts,
  };

  return applyExerciseSafetyGuardrail(structuredRoutine, userContext);
}
